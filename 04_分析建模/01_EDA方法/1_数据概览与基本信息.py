# 数据来源: seaborn 内置 titanic 数据集
# 依赖库最低版本要求: pandas>=2.0, numpy>=1.24, matplotlib>=3.7, seaborn>=0.13

import pandas as pd
import seaborn as sns
from pathlib import Path

# ============================================================
# 1. 数据概览与基本信息
# 探索性数据分析(EDA)的第一步是了解数据的基本结构和属性
# ============================================================

# 加载数据
df = sns.load_dataset('titanic')
print("=" * 60)
print("泰坦尼克号数据集 - 数据概览与基本信息")
print("=" * 60)

# --------------------------------------------------
# 1.1 df.head() - 查看前几行数据
# 默认显示前5行,快速了解数据的大致内容和格式
# --------------------------------------------------
print("\n【1.1 df.head() - 查看前5行数据】")
print(df.head())

# --------------------------------------------------
# 1.2 df.tail() - 查看后几行数据
# 默认显示后5行,检查数据末尾是否有异常
# --------------------------------------------------
print("\n【1.2 df.tail() - 查看后5行数据】")
print(df.tail())

# --------------------------------------------------
# 1.3 df.info() - 数据基本信息
# 显示列名、非空值数量、数据类型、内存占用等
# 是最常用的数据概览方法之一
# --------------------------------------------------
print("\n【1.3 df.info() - 数据基本信息】")
print(df.info())

# --------------------------------------------------
# 1.4 df.describe() - 描述性统计
# 对数值列计算均值、标准差、最值、四分位数等
# --------------------------------------------------
print("\n【1.4 df.describe() - 数值列描述性统计】")
print(df.describe())

# include='all' 可以包含所有类型的列
print("\n【1.4b df.describe(include='all') - 所有列描述性统计】")
print(df.describe(include='all'))

# --------------------------------------------------
# 1.5 df.shape - 数据维度
# 返回 (行数, 列数) 的元组
# --------------------------------------------------
print("\n【1.5 df.shape - 数据维度】")
print(f"数据集有 {df.shape[0]} 行, {df.shape[1]} 列")

# --------------------------------------------------
# 1.6 df.dtypes - 各列数据类型
# 了解每列的数据类型,检查是否有类型错误
# --------------------------------------------------
print("\n【1.6 df.dtypes - 各列数据类型】")
print(df.dtypes)

# --------------------------------------------------
# 1.7 df.columns - 列名列表
# 获取所有列名,方便后续操作
# --------------------------------------------------
print("\n【1.7 df.columns - 列名列表】")
print(df.columns.tolist())

# --------------------------------------------------
# 1.8 df.index - 索引信息
# 查看索引的类型和范围
# --------------------------------------------------
print("\n【1.8 df.index - 索引信息】")
print(f"索引类型: {type(df.index)}")
print(f"索引范围: {df.index.start} ~ {df.index.stop}")
print(f"索引步长: {df.index.step}")

# --------------------------------------------------
# 1.9 df.isnull().sum() - 缺失值统计
# 统计每列的缺失值数量,是数据清洗的重要依据
# --------------------------------------------------
print("\n【1.9 df.isnull().sum() - 缺失值统计】")
print(df.isnull().sum())

# 计算缺失值比例
print("\n【1.9b 缺失值比例】")
missing_pct = df.isnull().mean() * 100
print(missing_pct.round(2).astype(str) + '%')

# --------------------------------------------------
# 1.10 memory_usage() - 内存使用情况
# 查看每列的内存占用,大数据集优化时很有用
# --------------------------------------------------
print("\n【1.10 memory_usage() - 内存使用情况】")
print(df.memory_usage())

print(f"\n总内存占用: {df.memory_usage(deep=True).sum() / 1024:.2f} KB")

# --------------------------------------------------
# 补充: 数据类型分布与唯一值统计
# --------------------------------------------------
print("\n【补充: 数据类型分布】")
print(df.dtypes.value_counts())

print("\n【补充: 各列唯一值数量】")
for col in df.columns:
    print(f"  {col}: {df[col].nunique()} 个唯一值")

print("\n" + "=" * 60)
print("数据概览完成! 这些基本信息是后续深入分析的基础。")
print("=" * 60)
